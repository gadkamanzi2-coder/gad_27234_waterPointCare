/* 1. WATER_POINTS */
CREATE TABLE WATER_POINTS (
    water_point_id VARCHAR2(100) NOT NULL,
    latitude       NUMBER(10,7),
    longitude      NUMBER(10,7),
    elevation      NUMBER(8,2),
    geo_level_1    VARCHAR2(100),
    geo_level_2    VARCHAR2(100),
    geo_level_3    VARCHAR2(100),
    geo_level_4    VARCHAR2(100),
    geo_level_5    VARCHAR2(100),
    geo_level_6    VARCHAR2(100),
    geo_level_7    VARCHAR2(100)
)
TABLESPACE WATERPOINTCARE_DATA;


/* 2. WATER_POINT_ASSESSMENTS */
CREATE TABLE WATER_POINT_ASSESSMENTS (
    assessment_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    water_point_id VARCHAR2(100) NOT NULL,
    assessment_date DATE NOT NULL,
    level_of_service_score NUMBER(5,2),
    level_of_service VARCHAR2(50),
    has_improved_water_point VARCHAR2(20),
    improved_technology VARCHAR2(150),
    unimproved_technology VARCHAR2(150),
    is_functional CHAR(1),
    is_source_protected CHAR(1),
    number_of_users NUMBER(10),
    users_meet_standards CHAR(1),
    is_out_of_service_or_broken CHAR(1),
    breakage_frequency_meets_standard CHAR(1),
    breakage_days_meets_standard CHAR(1),
    monthly_outage_meets_standard CHAR(1),
    water_available_on_visit_day CHAR(1),
    seconds_to_fill_20_litres NUMBER(10,2),
    piped_or_handpump VARCHAR2(30),
    handpump_flow_rate NUMBER(10,3),
    piped_litres_per_person_per_day NUMBER(10,2),
    quantity_meets_standards CHAR(1),
    ecoli_meets_standard CHAR(1),
    residual_chlorine_meets_standard CHAR(1),
    bacteria_meets_standard CHAR(1),
    other_contaminant_present CHAR(1),
    other_contaminant_meets_standard CHAR(1),
    water_quality_meets_standards CHAR(1),
    overall_condition_is_good CHAR(1)
)
TABLESPACE WATERPOINTCARE_DATA;


/* 3. FAULT_REPORTS */
CREATE TABLE FAULT_REPORTS (
    fault_report_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    water_point_id VARCHAR2(100) NOT NULL,
    report_date DATE DEFAULT SYSDATE NOT NULL,
    fault_description VARCHAR2(1000) NOT NULL,
    fault_category VARCHAR2(100) NOT NULL,
    priority VARCHAR2(20) NOT NULL,
    status VARCHAR2(30) DEFAULT 'OPEN' NOT NULL,
    reported_by VARCHAR2(150),
    contact_information VARCHAR2(100),
    resolved_date DATE
)
TABLESPACE WATERPOINTCARE_DATA;


/* 4. MAINTENANCE_TEAMS */
CREATE TABLE MAINTENANCE_TEAMS (
    team_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    team_name VARCHAR2(150) NOT NULL,
    team_leader VARCHAR2(150),
    contact_phone VARCHAR2(30),
    email VARCHAR2(150),
    service_area VARCHAR2(150),
    team_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL
)
TABLESPACE WATERPOINTCARE_DATA;


/* 5. REPAIR_JOBS */
CREATE TABLE REPAIR_JOBS (
    repair_job_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fault_report_id NUMBER NOT NULL,
    team_id NUMBER,
    assigned_date DATE,
    start_date DATE,
    completion_date DATE,
    repair_description VARCHAR2(1000),
    repair_status VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
    repair_cost NUMBER(12,2),
    technician_name VARCHAR2(150),
    remarks VARCHAR2(1000)
)
TABLESPACE WATERPOINTCARE_DATA;


/* 6. SPARE_PARTS */
CREATE TABLE SPARE_PARTS (
    part_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    part_name VARCHAR2(150) NOT NULL,
    part_description VARCHAR2(500),
    part_category VARCHAR2(100),
    unit_cost NUMBER(12,2),
    quantity_in_stock NUMBER(10) DEFAULT 0 NOT NULL,
    minimum_stock_level NUMBER(10) DEFAULT 0 NOT NULL,
    part_status VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL
)
TABLESPACE WATERPOINTCARE_DATA;


/* 7. REPAIR_PART_USAGE */
CREATE TABLE REPAIR_PART_USAGE (
    repair_part_usage_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    repair_job_id NUMBER NOT NULL,
    part_id NUMBER NOT NULL,
    quantity_used NUMBER(10) NOT NULL,
    unit_cost_at_use NUMBER(12,2),
    usage_date DATE DEFAULT SYSDATE NOT NULL,
    remarks VARCHAR2(500)
)
TABLESPACE WATERPOINTCARE_DATA;


/* 8. STATUS_AUDIT_LOG */
CREATE TABLE STATUS_AUDIT_LOG (
    audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fault_report_id NUMBER NOT NULL,
    old_status VARCHAR2(30),
    new_status VARCHAR2(30) NOT NULL,
    changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    changed_by VARCHAR2(150),
    change_remarks VARCHAR2(500)
)
TABLESPACE WATERPOINTCARE_DATA;

